import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import {
  normalizeText,
  generateStableId,
  areDuplicateOrParaphrase,
  RedisHistoryAdapter,
  QuestionPoolExhaustedError,
  duplicatePrevention,
} from '../src/services/duplicatePrevention.js';
import { aiGenerator } from '../src/services/aiGenerator.js';
import { getRandomTriviaQuestion } from '../src/modes/triviaBank.js';
import { getRandomRareAnswer } from '../src/modes/rareAnswerBank.js';
import { GameEngine } from '../src/engine/GameEngine.js';
import { RoomManager } from '../src/managers/RoomManager.js';
import { Server } from 'socket.io';
import { createServer } from 'http';

describe('Shared Duplicate Prevention, Fingerprinting, and History Adapter Tests', () => {
  beforeEach(async () => {
    await duplicatePrevention.clearAll();
    aiGenerator.setForceProvider(null);
    aiGenerator.setGeminiClient(null);
    aiGenerator.setOpenAiClient(null);
  });

  afterEach(async () => {
    await duplicatePrevention.clearAll();
  });

  // =========================================================================
  // 1. Stable IDs, Fingerprinting & Paraphrase Detection
  // =========================================================================
  describe('1. Fingerprinting, Stable IDs, and Paraphrase Detection', () => {
    it('generates normalized text and identical stable IDs for reordered stopword questions', () => {
      const q1 = 'What is the capital city of France?';
      const q2 = 'What city is France\'s capital?';
      const q3 = 'What is the capital of France';

      const norm1 = normalizeText(q1);
      const norm2 = normalizeText(q2);
      expect(norm1).toBe('what is the capital city of france');
      expect(norm2).toBe('what city is france s capital');

      const id1 = generateStableId('trivia', q1);
      const id2 = generateStableId('trivia', q2);

      // Stable IDs for exact semantic question must match
      expect(id1).toBe(id2);
      expect(id1.startsWith('triv_')).toBe(true);

      const check = areDuplicateOrParaphrase(q1, q3);
      expect(check.isDuplicate).toBe(true);

      const rareId = generateStableId('rare_answer', 'Name an animal that can fly');
      expect(rareId.startsWith('rare_')).toBe(true);
    });

    it('detects exact duplicates regardless of casing, punctuation, and whitespace', () => {
      const res = areDuplicateOrParaphrase(
        '  What is the capital of France?  ',
        'what is the capital of france',
        'Paris',
        'Paris'
      );
      expect(res.isDuplicate).toBe(true);
      expect(res.reason).toBe('exact');
      expect(res.similarity).toBe(1.0);
    });

    it('detects closely paraphrased questions with inverted word order or synonymous phrasing', () => {
      const original = 'Which country has the longest total coastline in the world?';
      const paraphrase = 'What country in the world possesses the longest total coastline?';

      const check = areDuplicateOrParaphrase(original, paraphrase, 'Canada', 'Canada');
      expect(check.isDuplicate).toBe(true);
      expect(check.similarity).toBeGreaterThanOrEqual(0.65);
    });

    it('rejects duplicate question when question is rephrased and has the same correct answer', () => {
      const q1 = 'Which chemical element has the symbol "Au"?';
      const q2 = 'What element on the periodic table is represented by the symbol Au?';

      const check = areDuplicateOrParaphrase(q1, q2, 'Gold', 'Gold');
      expect(check.isDuplicate).toBe(true);
      expect(check.similarity).toBeGreaterThanOrEqual(0.5);
    });

    it('does not reject completely distinct questions in the same domain', () => {
      const q1 = 'What is the capital city of Australia?';
      const q2 = 'What is the capital city of Canada?';

      const check = areDuplicateOrParaphrase(q1, q2, 'Canberra', 'Ottawa');
      expect(check.isDuplicate).toBe(false);
      expect(check.similarity).toBeLessThan(0.65);
    });
  });

  // =========================================================================
  // 2. Cross-Provider Duplicate Prevention (Gemini -> OpenAI)
  // =========================================================================
  describe('2. Cross-Provider Shared History', () => {
    it('rejects questions from OpenAI if they were previously generated by Gemini in history', async () => {
      const roomCode = 'ROOM_CROSS_PROVIDER';

      // 1. Gemini generates and commits Question A
      const geminiQuestion = {
        question: 'Which planet in our solar system has the most moons?',
        correctAnswer: 'Saturn',
        incorrectAnswers: ['Jupiter', 'Uranus', 'Mars'],
        explanation: 'Saturn has 146 confirmed moons.',
        category: 'Science',
      };

      const mockGeminiClient = {
        getGenerativeModel: () => ({
          generateContent: async () => ({
            response: {
              text: () =>
                JSON.stringify({
                  questions: [
                    geminiQuestion,
                    {
                      question: 'What is the speed of light in vacuum?',
                      correctAnswer: '300,000 km/s',
                      incorrectAnswers: ['150,000 km/s', '450,000 km/s', '100,000 km/s'],
                      explanation: 'Light travels at ~300,000 km/s in vacuum.',
                      category: 'Science',
                    },
                    {
                      question: 'What is the hottest planet in the solar system?',
                      correctAnswer: 'Venus',
                      incorrectAnswers: ['Mercury', 'Mars', 'Jupiter'],
                      explanation: 'Venus has a dense greenhouse atmosphere.',
                      category: 'Science',
                    },
                  ],
                }),
            },
          }),
        }),
      };

      aiGenerator.setGeminiClient(mockGeminiClient);
      const batch1 = await aiGenerator.generateTriviaBatch({
        count: 3,
        difficulty: 'medium',
        roomCode,
      });

      expect(batch1).toHaveLength(3);
      // Commit reservation as happens when match starts
      await aiGenerator.commitBatchReservation(roomCode);

      // Verify questions are stored in shared duplicatePrevention history
      const history = await duplicatePrevention.getAdapter().getRecentEntries({ roomCode, type: 'trivia' });
      expect(history.length).toBeGreaterThanOrEqual(3);

      // 2. Now Gemini fails, forcing failover to OpenAI.
      // OpenAI attempts to return the same question (or close paraphrase) that Gemini generated.
      let openAiAttempts = 0;
      const mockOpenAiClient = {
        chat: {
          completions: {
            create: async () => {
              openAiAttempts++;
              if (openAiAttempts === 1) {
                // Returns duplicate of Gemini question + 2 others
                return {
                  choices: [
                    {
                      message: {
                        content: JSON.stringify({
                          questions: [
                            // Exact duplicate of Gemini question!
                            {
                              question: 'Which planet in our solar system has the most moons?',
                              correctAnswer: 'Saturn',
                              incorrectAnswers: ['Jupiter', 'Neptune', 'Mars'],
                              explanation: 'Saturn has over 140 moons.',
                              category: 'Science',
                            },
                            {
                              question: 'What is the powerhouse of the cell?',
                              correctAnswer: 'Mitochondria',
                              incorrectAnswers: ['Ribosome', 'Nucleus', 'Vacuole'],
                              explanation: 'Mitochondria generate ATP.',
                              category: 'Science',
                            },
                            {
                              question: 'What is absolute zero in Celsius?',
                              correctAnswer: '-273.15 C',
                              incorrectAnswers: ['-100 C', '-459 C', '-200 C'],
                              explanation: 'Absolute zero is -273.15 degrees Celsius.',
                              category: 'Science',
                            },
                          ],
                        }),
                      },
                    },
                  ],
                };
              }
              // Second attempt provides replacement for the rejected duplicate
              return {
                choices: [
                  {
                    message: {
                      content: JSON.stringify({
                        questions: [
                          {
                            question: 'What is the chemical symbol for table salt?',
                            correctAnswer: 'NaCl',
                            incorrectAnswers: ['KCl', 'NaOH', 'HCl'],
                            explanation: 'Table salt is sodium chloride (NaCl).',
                            category: 'Science',
                          },
                        ],
                      }),
                    },
                  },
                ],
              };
            },
          },
        },
      };

      // Force Gemini failure so failover to OpenAI occurs
      aiGenerator.setGeminiClient({
        getGenerativeModel: () => ({
          generateContent: async () => {
            throw new Error('Gemini Quota Exceeded (429)');
          },
        }),
      });
      aiGenerator.setOpenAiClient(mockOpenAiClient);

      const batch2 = await aiGenerator.generateTriviaBatch({
        count: 3,
        difficulty: 'medium',
        roomCode,
      });

      expect(batch2).toHaveLength(3);
      // Verify that the duplicate question from Gemini was NOT included in batch2
      const batch2Questions = batch2.map((q) => q.question.toLowerCase());
      expect(batch2Questions.some((q) => q.includes('most moons'))).toBe(false);
      expect(batch2Questions.some((q) => q.includes('powerhouse'))).toBe(true);
      expect(batch2Questions.some((q) => q.includes('table salt'))).toBe(true);
      // OpenAI was called twice because attempt 1 had a duplicate from Gemini history!
      expect(openAiAttempts).toBe(2);
    });
  });

  // =========================================================================
  // 3. Rematch History Preservation Across Matches
  // =========================================================================
  describe('3. Rematch History Preservation', () => {
    it('preserves room question history across rematches in GameEngine', async () => {
      const httpServer = createServer();
      const io = new Server(httpServer);
      const engine = new GameEngine(io);
      const roomManager = new RoomManager();

      const { room } = roomManager.createRoom('socket_host_1', {
        nickname: 'HostPlayer',
        avatar: 'avatar_1',
      });
      roomManager.updateSettings('socket_host_1', {
        settings: {
          roundCount: 3,
          selectedModes: ['trivia'],
          difficulty: 'medium',
        },
      });
      const roomCode = room.roomCode;
      roomManager.joinRoom('socket_guest_1', {
        roomCode,
        nickname: 'GuestPlayer',
        avatar: 'avatar_2',
      });

      let batchCount = 0;
      const mockGeminiClient = {
        getGenerativeModel: () => ({
          generateContent: async () => {
            batchCount++;
            if (batchCount === 1) {
              return {
                response: {
                  text: () =>
                    JSON.stringify({
                      questions: [
                        {
                          question: 'Which country has the largest land area in South America?',
                          correctAnswer: 'Brazil',
                          incorrectAnswers: ['Argentina', 'Peru', 'Colombia'],
                          explanation: 'Brazil is the largest country in South America.',
                          category: 'Geography',
                        },
                        {
                          question: 'What is the primary gas found in Earth atmosphere?',
                          correctAnswer: 'Nitrogen',
                          incorrectAnswers: ['Oxygen', 'Carbon Dioxide', 'Argon'],
                          explanation: 'Nitrogen makes up 78% of the atmosphere.',
                          category: 'Science',
                        },
                        {
                          question: 'Who was the first astronaut to step onto the Moon?',
                          correctAnswer: 'Neil Armstrong',
                          incorrectAnswers: ['Buzz Aldrin', 'Yuri Gagarin', 'Michael Collins'],
                          explanation: 'Neil Armstrong stepped on the Moon in July 1969.',
                          category: 'General Knowledge',
                        },
                      ],
                    }),
                },
              };
            }
            return {
              response: {
                text: () =>
                  JSON.stringify({
                    questions: [
                      {
                        question: 'What is the capital city of Japan?',
                        correctAnswer: 'Tokyo',
                        incorrectAnswers: ['Kyoto', 'Osaka', 'Nagoya'],
                        explanation: 'Tokyo is the capital of Japan.',
                        category: 'Geography',
                      },
                      {
                        question: 'Which element has atomic number one on the periodic table?',
                        correctAnswer: 'Hydrogen',
                        incorrectAnswers: ['Helium', 'Lithium', 'Carbon'],
                        explanation: 'Hydrogen has atomic number 1.',
                        category: 'Science',
                      },
                      {
                        question: 'In what year was the World Wide Web first introduced?',
                        correctAnswer: '1989',
                        incorrectAnswers: ['1975', '1995', '2001'],
                        explanation: 'Tim Berners-Lee proposed the web in 1989.',
                        category: 'Technology',
                      },
                    ],
                  }),
              },
            };
          },
        }),
      };

      aiGenerator.setGeminiClient(mockGeminiClient);

      // 1. Play Game 1
      await engine.startGame(room);
      expect(room.status).toBe('PREPARING_QUESTIONS');

      // Wait for preparation to complete and countdown to commit reservation
      await new Promise((r) => setTimeout(r, 100));
      expect(room.status).toBe('COUNTDOWN');

      // Verify Game 1 questions are committed in duplicatePrevention
      const game1Entries = await duplicatePrevention.getAdapter().getRecentEntries({ roomCode, type: 'trivia' });
      expect(game1Entries.length).toBeGreaterThanOrEqual(3);

      // 2. Game ends and host calls playAgain (rematch)
      engine.playAgain(room);
      expect(room.status).toBe('LOBBY');

      // 3. Start Rematch (Game 2)
      await engine.startGame(room);
      await new Promise((r) => setTimeout(r, 100));
      expect(room.status).toBe('COUNTDOWN');

      // Verify that room history in duplicatePrevention now contains both Game 1 and Game 2 entries
      const allEntries = await duplicatePrevention.getAdapter().getRecentEntries({ roomCode, type: 'trivia' });
      expect(allEntries.length).toBe(6);

      engine.clearAll();
      httpServer.close();
    });
  });

  // =========================================================================
  // 4. Concurrent Preparation and Leases / Reservations
  // =========================================================================
  describe('4. Concurrent Preparation and Reservations', () => {
    it('prevents concurrent match preparations from reserving the same questions', async () => {
      const roomA = 'ROOM_CONCURRENT_A';
      const roomB = 'ROOM_CONCURRENT_B';

      const sharedCandidate = {
        text: 'What is the largest ocean on planet Earth?',
        correctAnswer: 'Pacific Ocean',
        category: 'Geography',
        difficulty: 'easy' as const,
      };

      // Room A reserves sharedCandidate
      const resA = await duplicatePrevention.checkAndReserve({
        roomCode: roomA,
        type: 'trivia',
        candidates: [sharedCandidate],
      });
      expect(resA.success).toBe(true);
      expect(resA.reservationId).toBeDefined();

      // Room B concurrently attempts to reserve the exact same candidate
      const resB = await duplicatePrevention.checkAndReserve({
        roomCode: roomB,
        type: 'trivia',
        candidates: [sharedCandidate],
      });

      // Must be rejected as duplicate collision with active reservation!
      expect(resB.success).toBe(false);
      expect(resB.rejectedDuplicates?.length).toBe(1);
      expect(resB.rejectedDuplicates?.[0].reason).toBe('exact');

      // Releasing Room A's reservation permits Room B to acquire it
      await duplicatePrevention.releaseReservation(resA.reservationId!);

      const resBAfterRelease = await duplicatePrevention.checkAndReserve({
        roomCode: roomB,
        type: 'trivia',
        candidates: [sharedCandidate],
      });
      expect(resBAfterRelease.success).toBe(true);
    });
  });

  // =========================================================================
  // 5. Unavailable Storage (Redis down -> in-memory fallback)
  // =========================================================================
  describe('5. Unavailable Storage and Graceful Degradation', () => {
    it('gracefully degrades to in-memory fallback when Redis is unreachable without crashing', async () => {
      // Connect to a non-existent port where no Redis service is running
      const unreachableUrl = 'redis://127.0.0.1:54321';
      const redisAdapter = new RedisHistoryAdapter(unreachableUrl, 100, 20);

      // System must not throw; isAvailable() is false
      expect(redisAdapter.name).toBe('redis');
      expect(redisAdapter.isAvailable()).toBe(false);

      // Operations succeed transparently using internal fallback
      const candidate = {
        id: 'triv_test_redis_fallback',
        type: 'trivia' as const,
        fingerprint: 'what capital france',
        normalizedText: 'what is the capital of france',
        tokens: ['capital', 'france'],
        category: 'Geography',
        recordedAt: Date.now(),
        expiresAt: Date.now() + 60000,
        roomCode: 'REDIS_FALLBACK_ROOM',
      };

      await redisAdapter.addEntries([candidate]);
      const entries = await redisAdapter.getRecentEntries({ roomCode: 'REDIS_FALLBACK_ROOM' });
      expect(entries).toHaveLength(1);
      expect(entries[0].normalizedText).toBe('what is the capital of france');

      await redisAdapter.close();
    });
  });

  // =========================================================================
  // 6. Exhausted Question Pools (Explicit Error, Never Silently Recycled)
  // =========================================================================
  describe('6. Exhausted Question Pools', () => {
    it('throws QuestionPoolExhaustedError when offline Trivia pool is exhausted', () => {
      const usedIds = new Set<string>();
      // Collect all questions for 'hard' difficulty
      let count = 0;
      expect(() => {
        // Repeatedly fetch hard questions until bank is depleted
        for (let i = 0; i < 200; i++) {
          const q = getRandomTriviaQuestion(usedIds, 'hard', false);
          usedIds.add(q.id);
          count++;
        }
      }).toThrowError(QuestionPoolExhaustedError);

      expect(count).toBeGreaterThan(0);
    });

    it('throws QuestionPoolExhaustedError when offline Rare Answer pool is exhausted', () => {
      const usedIds = new Set<string>();
      expect(() => {
        // Repeatedly fetch hard rare answer prompts until bank is depleted
        for (let i = 0; i < 50; i++) {
          const r = getRandomRareAnswer(usedIds, 'hard', false);
          usedIds.add(r.id);
        }
      }).toThrowError(QuestionPoolExhaustedError);
    });

    it('explains exhaustion in generateOfflineBatch instead of silently recycling content', async () => {
      const roomCode = 'ROOM_EXHAUSTION_EXPLAIN';
      // Populate room history with all available questions for hard difficulty
      const pool = getRandomTriviaQuestion(new Set(), 'hard');
      expect(pool).toBeDefined();

      const usedAll = new Set<string>();
      for (let i = 0; i < 100; i++) {
        try {
          const q = getRandomTriviaQuestion(usedAll, 'hard', false);
          usedAll.add(q.id);
        } catch {
          break; // reached bank limit
        }
      }

      await expect(
        aiGenerator.generateOfflineBatch(5, 'hard', usedAll, roomCode)
      ).rejects.toThrowError(QuestionPoolExhaustedError);
    });
  });
});
